import { spawn } from "child_process";
import fs from "fs";
import path from "path";
import { parseArgs } from "util";
import { InstanceConfig, listInstances, loadInstance } from "../instance";
import { Layout } from "../layout";
import { RunState, isProcessAlive, pidFileState, waitUntil, writePidFile } from "../proc";
import { lastLines } from "./files";
import type { Command, Out } from "./main";

const STARTUP_CHECK_MS = 2000;
const STOP_TIMEOUT_MS = 10_000;

const pidFile = (layout: Layout): string => path.join(layout.stateDir, "caddy.pid");
const outputFile = (layout: Layout): string => path.join(layout.logsDir, "caddy.stdout");

export function caddyState(layout: Layout): { state: RunState; pid: number | null } {
  return pidFileState(pidFile(layout));
}

// Caddy runs in a session of its own, as the regular user: closing the terminal does not stop it.
export async function startCaddy(layout: Layout, out: Out): Promise<boolean> {
  fs.mkdirSync(layout.logsDir, { recursive: true });
  const fd = fs.openSync(outputFile(layout), "w"); // emptied at each start
  const binary = process.env.CADDY_BINARY ?? "caddy";
  const child = spawn(binary, ["run", "--config", layout.caddyfile, "--adapter", "caddyfile"], {
    detached: true,
    stdio: ["ignore", fd, fd],
    cwd: layout.root,
  });
  fs.closeSync(fd);
  const failed = new Promise<NodeJS.ErrnoException>((resolve) => child.on("error", resolve));
  child.unref();
  if (child.pid !== undefined) writePidFile(pidFile(layout), child.pid);

  const early = await Promise.race([failed, new Promise<null>((resolve) => setTimeout(() => resolve(null), STARTUP_CHECK_MS))]);
  if (early) {
    out(early.code === "ENOENT" ? "caddy not found: install it (see INSTALL.md)" : `caddy: ${early.message}`);
    return false;
  }
  if (child.pid !== undefined && isProcessAlive(child.pid)) {
    out(`caddy: running (pid ${child.pid})`);
    return true;
  }
  out("caddy: failed to start:");
  for (const line of lastLines(outputFile(layout), 20)) out(`  ${line}`);
  return false;
}

export async function stopCaddy(layout: Layout, out: Out): Promise<void> {
  const { state, pid } = caddyState(layout);
  if (state === "running" && pid !== null) {
    try {
      process.kill(pid, "SIGTERM");
    } catch {
      // already gone
    }
    if (!(await waitUntil(() => !isProcessAlive(pid), STOP_TIMEOUT_MS))) {
      try {
        process.kill(pid, "SIGKILL");
      } catch {
        // already gone
      }
    }
    out("caddy: stopped");
  } else if (state === "crashed") {
    out("caddy: was crashed (stale pid file removed)");
  }
  fs.rmSync(pidFile(layout), { force: true });
}

const DOMAIN_RE = /^(?=.{1,253}$)([a-z0-9]([a-z0-9-]*[a-z0-9])?\.)+[a-z]{2,}$/i;

// HTTPS for the domain on port 8443 (the Freebox forwards its port 443 to it), and one route /<instance>/...
// per public instance, to the listener of that instance on 127.0.0.1. LAN-only instances have no route.
export function renderCaddyfile(layout: Layout, domain: string, instances: InstanceConfig[]): string {
  const routes = instances
    .filter((inst) => inst.publicEnabled)
    .sort((a, b) => a.name.localeCompare(b.name))
    .flatMap((inst) => [
      `\thandle_path /${inst.name}/* {`,
      `\t\treverse_proxy 127.0.0.1:${inst.publicPort} {`,
      "\t\t\tflush_interval -1",
      "\t\t}",
      "\t}",
    ]);
  return [
    "# Generated by ./proof-server.sh caddyfile — do not edit, run the command again instead.",
    "{",
    "\thttp_port 8080",
    "\thttps_port 8443",
    "\tadmin localhost:2019",
    "\tstorage file_system {",
    `\t\troot ${path.join(layout.stateDir, "caddy")}`,
    "\t}",
    "\tlog {",
    `\t\toutput file ${path.join(layout.logsDir, "caddy.log")} {`,
    "\t\t\troll_size 5MiB",
    "\t\t\troll_keep 3",
    "\t\t}",
    "\t}",
    "}",
    "",
    `${domain} {`,
    "\ttls {",
    "\t\tissuer acme {",
    "\t\t\tdisable_http_challenge",
    "\t\t}",
    "\t}",
    "\trequest_body {",
    "\t\tmax_size 1MB",
    "\t}",
    ...routes,
    "\thandle {",
    '\t\trespond "Not found" 404',
    "\t}",
    "}",
    "",
  ].join("\n");
}

export const caddyfileCommand: Command = async (layout, args, out) => {
  let domain: string | undefined;
  try {
    domain = parseArgs({ args, options: { domain: { type: "string" } } }).values.domain;
  } catch (err) {
    out(`caddyfile: ${(err as Error).message}`);
    return 1;
  }
  if (!domain) {
    out("Usage: ./proof-server.sh caddyfile --domain <your-name>.duckdns.org");
    return 1;
  }
  if (!DOMAIN_RE.test(domain)) {
    out(`"${domain}" is not a valid domain name (example: myproof.duckdns.org)`);
    return 1;
  }
  const publicInstances = listInstances(layout)
    .map((name) => loadInstance(layout, name))
    .filter((inst) => inst.publicEnabled);
  if (publicInstances.length === 0) {
    out("No public instance (PUBLIC_ENABLED=true) in instances/");
    return 1;
  }

  fs.mkdirSync(path.dirname(layout.caddyfile), { recursive: true });
  fs.writeFileSync(layout.caddyfile, renderCaddyfile(layout, domain, publicInstances));
  out(`Wrote ${layout.caddyfile}`);
  out("Public addresses:");
  for (const inst of publicInstances) out(`  https://${domain}/${inst.name}/prove`);
  out("Freebox: forward TCP 443 to this machine, port 8443.");
  out("Then run ./proof-server.sh start (or restart if the instances are already running).");
  return 0;
};
